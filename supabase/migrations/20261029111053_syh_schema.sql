-- ── 1. Permisos ──────────────────────────────────────────────
-- Calcadas de las de Calidad (20260916090409). Tienen que decir lo mismo que
-- lib/seguridadHigiene/auth.ts: cuando no coincidieron, en la 029, un
-- admin_sistema veía los botones y RLS le devolvía listas vacías.

create or replace function public.tiene_acceso_syh()
returns boolean
language sql stable security definer set search_path = public
as $$
  select coalesce(
    es_admin() or exists (
      select 1 from usuario_modulos
      where usuario_id = auth.uid() and modulo = 'seguridad_higiene'
    ),
    false
  )
$$;

create or replace function public.puede_editar_syh()
returns boolean
language sql stable security definer set search_path = public
as $$
  select coalesce(
    es_admin() or exists (
      select 1 from usuario_modulos
      where usuario_id = auth.uid() and modulo = 'seguridad_higiene'
        and nivel in ('edicion', 'admin')
    ),
    false
  )
$$;

create or replace function public.es_admin_syh()
returns boolean
language sql stable security definer set search_path = public
as $$
  select coalesce(
    es_admin() or exists (
      select 1 from usuario_modulos
      where usuario_id = auth.uid() and modulo = 'seguridad_higiene' and nivel = 'admin'
    ),
    false
  )
$$;

