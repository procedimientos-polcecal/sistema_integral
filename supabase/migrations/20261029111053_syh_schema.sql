-- CONFIRMADO. Las funciones de abajo mencionan 'seguridad_higiene', y un valor
-- de enum recién agregado no se puede usar en la misma transacción (55P04).
--
-- Reemplaza el Excel de condiciones inseguras (`21-10-26.xlsm`), que es de otra
-- empresa, tiene la fórmula del nivel rota en todas las filas menos la 10 y
-- nadie mantiene. Una condición insegura es algo que se ve parado frente al
-- problema —una protección que falta, un piso roto— y se carga desde el
-- teléfono; después alguien la evalúa, la asigna y la cierra desde la
-- computadora.
--
-- UNA CONDICIÓN NACE SIN EVALUAR, y eso es el diseño y no un hueco. Por eso los
-- cinco puntajes, el responsable, la fecha máxima y la fecha de ejecución
-- admiten null, y por eso los `check` de los puntajes también: en SQL un `check`
-- con un null adentro da "desconocido" y la fila pasa, que es exactamente lo
-- que se quiere. Lo que NO se admite es un valor fuera de la escala.
--
-- LAS TRES COLUMNAS CALCULADAS SON GENERADAS Y NO SE ESCRIBEN NUNCA. Guardar el
-- nivel a mano sería tener dos verdades —el nivel y los puntajes que lo
-- explican— y en el Excel eso ya salió mal.
--
--   * `nivel_riesgo` REPITE LA SUMA en vez de multiplicar `probabilidad` por
--     `gravedad`: Postgres no deja que una columna generada referencie a otra
--     generada.
--   * Con un puntaje en null, la suma da null y el nivel también. Es lo que se
--     quiere: una condición evaluada a medias no sale de «sin evaluar» con una
--     clasificación inventada. Si alguien "arregla" esto con un coalesce(…, 0),
--     `nivel_riesgo` pasa a ser 0 y la fila parece tener un riesgo que nadie
--     midió. La Tarea 2 del plan tiene un paso que lo comprueba contra la base.
--
-- EL ESTADO (Pendiente / Cerrada / Vencida) NO ES UNA COLUMNA: se deriva de
-- `fecha_ejecucion` y `fecha_maxima` en lib/seguridadHigiene/condicion.ts.
-- Guardarlo sería permitir una fila «Pendiente» con la fecha máxima en el mes
-- pasado.
--
-- EL LUGAR ES OPCIONAL EN LA TABLA: `num_nonnulls(sector_id, equipo_id) <= 1` y
-- no `= 1`. Que sea obligatorio es regla del alta desde el teléfono. Si la
-- tabla lo exigiera, las 44 condiciones del Excel que entran con el lugar sin
-- reconocer no podrían entrar: la regla del repo es dejar null antes que
-- enlazar al que se le parece.
--
-- `clave` ES LA IDEMPOTENCIA DE LA COLA OFFLINE. El teléfono reintenta cuando
-- vuelve la señal, y la pantalla y el service worker pueden despertar a la vez:
-- sin una clave única, la misma carga entra dos veces. Va acá y no en otra
-- migración porque la ruta de alta la necesita y una migración aplicada no se
-- edita. Es un `unique` común y no un índice parcial: los null no chocan entre
-- sí, y un parcial no sirve como destino de ON CONFLICT (README, trampa #2).
--
-- `numero` ES `generated by default` Y NO `always`, a propósito: el script que
-- migra las 44 del Excel tiene que poder conservar el N° de la planilla. Eso
-- tiene un costo que hay que pagar a mano: un insert con número explícito NO
-- adelanta la secuencia, así que ese script termina con un `setval` sobre ella;
-- si se olvida, la primera condición cargada desde el teléfono choca con el
-- `unique` de `numero`.
--
-- LAS POLICIES LLAMAN A SU FUNCIÓN ENVUELTA: `(select tiene_acceso_syh())` y no
-- `tiene_acceso_syh()`. Postgres evalúa el USING una vez por fila aunque la
-- función sea STABLE; el subselect lo convierte en un InitPlan que se evalúa
-- una vez. Pelada no rompe nada y no avisa: la tabla simplemente empieza a
-- costar proporcional a sus filas (el 14/10/2026 tuvo a `calculos_diarios` en
-- timeout; ver 20261014090512 y 20261014104956).
--
-- RLS NO SABE DE COLUMNAS, y la spec pide que `edicion` corrija sólo la primera
-- etapa y que evaluar, asignar y cerrar sea de `admin`. Las policies de
-- `syh_condiciones` solas dejarían a un `edicion` escribir los puntajes con un
-- cliente de Supabase en la mano. Por eso hay un trigger al final (sección 6)
-- que lo rechaza. No corre para el cliente admin ni para el editor SQL
-- (`auth.uid()` es null): ahí RLS tampoco corre y es donde viven los scripts y
-- el cron.
--
-- Diseño: docs/superpowers/specs/2026-10-29-seguridad-e-higiene-design.md
