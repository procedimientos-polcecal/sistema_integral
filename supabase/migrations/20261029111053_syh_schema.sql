-- ── 3. Las condiciones inseguras ─────────────────────────────

create table if not exists public.syh_condiciones (
  id                 uuid primary key default gen_random_uuid(),
  numero             integer generated by default as identity unique,
  clave              text unique,

  -- Lo que carga el teléfono
  sector_id          uuid references public.sectores(id),
  equipo_id          uuid references public.equipos(id),
  detectada_el       date not null default current_date,
  detectada_por      uuid references public.usuarios(id),
  descripcion        text not null,
  peligro_id         uuid references public.syh_peligros(id),
  accion_propuesta   text,
  prioridad          integer,

  -- Lo que se completa después, desde la gestión: todo nullable
  responsable_id     uuid references public.usuarios(id),
  fecha_maxima       date,
  fecha_ejecucion    date,
  requiere_inversion boolean,
  observaciones      text,
  frecuencia         integer,
  antecedentes       integer,
  controles          integer,
  magnitud_dano      integer,
  legislacion        integer,

  -- Lo calculado. Nunca se escribe.
  probabilidad  integer generated always as (frecuencia + antecedentes + controles) stored,
  gravedad      integer generated always as (magnitud_dano + legislacion) stored,
  nivel_riesgo  integer generated always as ((frecuencia + antecedentes + controles) * (magnitud_dano + legislacion)) stored,

  creada_en          timestamptz not null default now(),
  actualizada_en     timestamptz,

  constraint syh_cond_lugar        check (num_nonnulls(sector_id, equipo_id) <= 1),
  constraint syh_cond_prioridad    check (prioridad     in (1, 2, 3)),
  constraint syh_cond_frecuencia   check (frecuencia    in (1, 2, 3)),
  constraint syh_cond_antecedentes check (antecedentes  in (1, 2, 3)),
  constraint syh_cond_controles    check (controles     in (1, 3, 5)),
  constraint syh_cond_magnitud     check (magnitud_dano in (3, 7, 9)),
  constraint syh_cond_legislacion  check (legislacion   in (1, 3, 5))
);

create index if not exists syh_cond_detectada on public.syh_condiciones (detectada_el);

-- ── 4. Las fotos ─────────────────────────────────────────────
-- Una tabla aparte y no un array de links en la condición: la planilla ya tiene
-- filas con dos fotos y una con más, y el respaldo en Drive necesita saber, por
-- foto, si ya viajó. `respaldada_en_drive_el` queda en null hasta que el cron
-- corra; la app lee siempre de Storage.

create table if not exists public.syh_fotos (
  id                     uuid primary key default gen_random_uuid(),
  condicion_id           uuid not null references public.syh_condiciones(id) on delete cascade,
  ruta                   text not null,
  subida_por             uuid references public.usuarios(id),
  subida_el              timestamptz not null default now(),
  respaldada_en_drive_el timestamptz
);

create index if not exists syh_fotos_condicion on public.syh_fotos (condicion_id);

-- ── 5. RLS ───────────────────────────────────────────────────

alter table public.syh_peligros     enable row level security;
alter table public.syh_condiciones  enable row level security;
alter table public.syh_fotos        enable row level security;

drop policy if exists syh_peligros_leer on public.syh_peligros;
create policy syh_peligros_leer on public.syh_peligros
  for select using ((select tiene_acceso_syh()));

drop policy if exists syh_peligros_escribir on public.syh_peligros;
create policy syh_peligros_escribir on public.syh_peligros
  for all using ((select es_admin_syh())) with check ((select es_admin_syh()));

drop policy if exists syh_cond_leer on public.syh_condiciones;
create policy syh_cond_leer on public.syh_condiciones
  for select using ((select tiene_acceso_syh()));

-- Cargar una condición: `edicion`. Que no entre ya evaluada o cerrada lo
-- impone el trigger de la sección 6.
drop policy if exists syh_cond_insertar on public.syh_condiciones;
create policy syh_cond_insertar on public.syh_condiciones
  for insert with check ((select puede_editar_syh()));

-- Corregir la primera etapa: `edicion`, y sólo mientras la condición no esté
-- cerrada. El WITH CHECK (que por omisión es igual al USING) impide además que
-- un editor la cierre al actualizarla. Qué columnas puede tocar lo impone el
-- trigger de la sección 6.
drop policy if exists syh_cond_corregir on public.syh_condiciones;
create policy syh_cond_corregir on public.syh_condiciones
  for update
  using ((select puede_editar_syh()) and fecha_ejecucion is null)
  with check ((select puede_editar_syh()) and fecha_ejecucion is null);

-- Evaluar, asignar, cerrar, reabrir y borrar: `admin`.
drop policy if exists syh_cond_gestionar on public.syh_condiciones;
create policy syh_cond_gestionar on public.syh_condiciones
  for all using ((select es_admin_syh())) with check ((select es_admin_syh()));

drop policy if exists syh_fotos_leer on public.syh_fotos;
create policy syh_fotos_leer on public.syh_fotos
  for select using ((select tiene_acceso_syh()));

-- Agregar o sacar fotos: `edicion`, mientras la condición no esté cerrada.
--
-- Al agregar, `respaldada_en_drive_el` TIENE QUE VENIR EN NULL: es del cron de
-- respaldo, y un valor falseado hace que el respaldo saltee esa foto, que es
-- el único campo que no se recupera después. Y `subida_por`, si viene, es quien
-- sube: no se firma una foto a nombre de otro. Va en el WITH CHECK y no en un
-- trigger porque la tabla no tiene otra regla de columnas y esto cabe en una
-- línea; el cliente admin (el cron, los scripts) no pasa por acá.
drop policy if exists syh_fotos_agregar on public.syh_fotos;
create policy syh_fotos_agregar on public.syh_fotos
  for insert with check (
    (select puede_editar_syh())
    and respaldada_en_drive_el is null
    and (subida_por is null or subida_por = (select auth.uid()))
    and exists (
      select 1 from public.syh_condiciones c
      where c.id = condicion_id and c.fecha_ejecucion is null
    )
  );

drop policy if exists syh_fotos_sacar on public.syh_fotos;
create policy syh_fotos_sacar on public.syh_fotos
  for delete using (
    (select puede_editar_syh())
    and exists (
      select 1 from public.syh_condiciones c
      where c.id = condicion_id and c.fecha_ejecucion is null
    )
  );

-- El resto (corregir una foto, y todo sobre una condición cerrada): `admin`.
-- `respaldada_en_drive_el` la escribe el cron con el cliente admin.
drop policy if exists syh_fotos_gestionar on public.syh_fotos;
create policy syh_fotos_gestionar on public.syh_fotos
  for all using ((select es_admin_syh())) with check ((select es_admin_syh()));

-- ── 6. Lo que RLS no puede decir: qué columnas toca cada nivel ──
-- `edicion` carga y corrige la primera etapa; evaluar el riesgo, asignar y
-- cerrar es de `admin`. Una policy ve la fila entera, no la columna, así que
-- esto se hace acá.
--
-- Además de esas diez columnas de gestión, el trigger cuida tres que son de la
-- identidad de la fila y que un `edicion` no tiene motivo para tocar:
--   * `numero`: es el correlativo visible. Como es `generated by default`, un
--     insert con número explícito NO adelanta la secuencia, y más tarde el
--     número autoasignado choca con el `unique` y la carga desde el teléfono
--     falla con 23505, un error que no le dice nada a quien está en la planta.
--   * `clave`: la idempotencia de la cola offline. Se fija al crear.
--   * `detectada_por`: es quien carga; no se firma una carga a nombre de otro.
--
-- Cómo se reconoce un `numero` explícito: en un BEFORE INSERT el default de la
-- identidad ya corrió, así que `new.numero` trae igual un valor y no se puede
-- preguntar «¿vino null?». Se lo compara con `currval` de la secuencia: si el
-- default sacó el número, `currval` es ése; si lo puso la persona, o no es el
-- mismo, o la sesión nunca llamó a `nextval` y `currval` tira 55000 (que se
-- trata como «explícito»). Si el explícito coincidiera con un `currval` viejo
-- de la misma conexión, esa fila ya existe y el `unique` lo rechaza igual.
--
-- `auth.uid() is null` es el cliente admin (rutas con service role, el cron, el
-- script de migración) o el editor SQL: ahí RLS no corre y no se le pone un
-- freno que la app no necesita. Los permisos de esas rutas los comprueba la
-- ruta, con lib/seguridadHigiene/auth.ts.

create or replace function public.syh_condiciones_proteger_gestion()
returns trigger
language plpgsql set search_path = public
as $$
declare
  toca_gestion boolean;
  toca_identidad boolean;
begin
  if auth.uid() is null or (select es_admin_syh()) then
    return new;
  end if;

  if tg_op = 'INSERT' then
    begin
      toca_identidad := new.numero is distinct from currval(pg_get_serial_sequence('public.syh_condiciones', 'numero'));
    exception when object_not_in_prerequisite_state then
      toca_identidad := true;
    end;
    toca_identidad := toca_identidad
      or (new.detectada_por is not null and new.detectada_por <> auth.uid());

    toca_gestion :=
      new.responsable_id is not null or new.fecha_maxima is not null
      or new.fecha_ejecucion is not null or new.requiere_inversion is not null
      or new.observaciones is not null
      or new.frecuencia is not null or new.antecedentes is not null
      or new.controles is not null or new.magnitud_dano is not null
      or new.legislacion is not null;
  else
    toca_identidad :=
      new.numero is distinct from old.numero
      or new.clave is distinct from old.clave
      or new.detectada_por is distinct from old.detectada_por;

    toca_gestion :=
      new.responsable_id    is distinct from old.responsable_id
      or new.fecha_maxima       is distinct from old.fecha_maxima
      or new.fecha_ejecucion    is distinct from old.fecha_ejecucion
      or new.requiere_inversion is distinct from old.requiere_inversion
      or new.observaciones      is distinct from old.observaciones
      or new.frecuencia         is distinct from old.frecuencia
      or new.antecedentes       is distinct from old.antecedentes
      or new.controles          is distinct from old.controles
      or new.magnitud_dano      is distinct from old.magnitud_dano
      or new.legislacion        is distinct from old.legislacion;
  end if;

  if toca_identidad then
    raise exception 'El número, la clave y quién detectó una condición no se pueden cambiar'
      using errcode = '42501';
  end if;

  if toca_gestion then
    raise exception 'Evaluar el riesgo, asignar y cerrar una condición requiere nivel admin en Seguridad e Higiene'
      using errcode = '42501';
  end if;

  return new;
end;
$$;

drop trigger if exists syh_condiciones_proteger_gestion on public.syh_condiciones;
create trigger syh_condiciones_proteger_gestion
  before insert or update on public.syh_condiciones
  for each row execute function public.syh_condiciones_proteger_gestion();
